// Package opgen turns an OpenAPI 3.1 document into the Go operation table of package api.
package opgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

type operation struct {
	ID, Method, Path, Summary string
	PathParams, QueryParams   []string
	Body                      bool
}

// Generate returns gofmt'ed Go source for operations_gen.go.
func Generate(doc []byte) ([]byte, error) {
	var d struct {
		Info struct {
			Title   string `json:"title"`
			Version string `json:"version"`
		} `json:"info"`
		Paths map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(doc, &d); err != nil {
		return nil, fmt.Errorf("OpenAPI: %w", err)
	}
	var ops []operation
	for path, item := range d.Paths {
		for method, raw := range item {
			switch method {
			case "get", "put", "post", "patch", "delete":
			default:
				continue
			}
			var o struct {
				OperationID string `json:"operationId"`
				Summary     string `json:"summary"`
				Parameters  []struct {
					Name string `json:"name"`
					In   string `json:"in"`
				} `json:"parameters"`
				RequestBody json.RawMessage `json:"requestBody"`
			}
			if err := json.Unmarshal(raw, &o); err != nil {
				return nil, fmt.Errorf("%s %s: %w", method, path, err)
			}
			if o.OperationID == "" {
				return nil, fmt.Errorf("%s %s has no operationId", method, path)
			}
			op := operation{ID: o.OperationID, Method: strings.ToUpper(method), Path: path, Summary: o.Summary, Body: len(o.RequestBody) > 0}
			for _, p := range o.Parameters {
				switch p.In {
				case "path":
					op.PathParams = append(op.PathParams, p.Name)
				case "query":
					op.QueryParams = append(op.QueryParams, p.Name)
				}
			}
			sort.Strings(op.QueryParams)
			ops = append(ops, op)
		}
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].ID < ops[j].ID })
	var b bytes.Buffer
	b.WriteString("// Code generated by vrx-opgen from packages/api-client/openapi.json. DO NOT EDIT.\n\n")
	b.WriteString("package api\n\n")
	fmt.Fprintf(&b, "// SpecVersion is info.version of the OpenAPI document the table was generated from.\nconst SpecVersion = %q\n\n", d.Info.Version)
	b.WriteString("// Operations is every REST operation of the API, by operationId.\nvar Operations = map[string]Operation{\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "\t%q: {ID: %q, Method: %q, Path: %q, Summary: %q, PathParams: %s, QueryParams: %s, Body: %t},\n",
			o.ID, o.ID, o.Method, o.Path, o.Summary, strs(o.PathParams), strs(o.QueryParams), o.Body)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func strs(s []string) string {
	if len(s) == 0 {
		return "nil"
	}
	q := make([]string, len(s))
	for i, x := range s {
		q[i] = fmt.Sprintf("%q", x)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
